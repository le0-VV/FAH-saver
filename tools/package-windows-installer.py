#!/usr/bin/env python3
"""Build the per-user NSIS setup from a hash-verified Windows release folder."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / "platform/windows/installer"


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def nsis_escape(text):
    if any(character in text for character in '\r\n\0"'):
        raise ValueError("NSIS paths cannot contain a newline, NUL or quote")
    return text


def pe_machine(path):
    data = path.read_bytes()
    if len(data) < 64 or data[:2] != b"MZ":
        raise ValueError("Expected a Windows PE executable")
    offset = struct.unpack_from("<I", data, 0x3C)[0]
    if offset + 24 > len(data) or data[offset:offset + 4] != b"PE\0\0":
        raise ValueError("Invalid Windows PE header")
    return struct.unpack_from("<H", data, offset + 4)[0]


def validate_payload(payload):
    payload = payload.resolve(strict=True)
    manifest = json.loads((payload / "manifest.json").read_text())
    version = manifest["version"]
    if not isinstance(version, str) or not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("The Windows release needs a three-part numeric version")
    if any(int(part) > 65535 for part in version.split(".")):
        raise ValueError("Version components must fit the Windows version resource")
    names = json.loads((INSTALLER / "payload-files.json").read_text())
    if not names or len(names) != len(set(names)):
        raise ValueError("Installer payload inventory is empty or duplicated")
    checked = {}
    for name in names:
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts or "\\" in name:
            raise ValueError("Invalid installer payload path")
        file = payload / relative
        if not file.is_file() or file.is_symlink() or not file.resolve().is_relative_to(payload):
            raise ValueError(f"Missing or linked installer payload: {name}")
        actual = sha256(file)
        if actual != manifest["files"].get(name):
            raise ValueError(f"Payload hash mismatch: {name}")
        checked[name] = actual
    if pe_machine(payload / "FAHSaver.scr") != 0x8664:
        raise ValueError("FAHSaver.scr must be a Windows x64 executable")
    return manifest, checked


def payload_include(payload, names):
    lines = ["; Generated by package-windows-installer.py", "!macro FAH_ExtractPayload"]
    for name in names:
        relative = Path(name)
        subdirectory = str(relative.parent).replace("/", "\\")
        output = "$PLUGINSDIR\\payload" + ("\\" + subdirectory if subdirectory != "." else "")
        lines += [f'  SetOutPath "{output}"', f'  File "{nsis_escape(str(payload / relative))}"']
    lines += ["!macroend", "", "!macro FAH_PayloadFiles ACTION"]
    for name in names:
        windows_name = name.replace("/", "\\")
        lines.append(f'  !insertmacro ${{ACTION}} "{windows_name}"')
    lines += ["!macroend", "", "!macro FAH_ManagedFiles ACTION",
              "  !insertmacro FAH_PayloadFiles ${ACTION}",
              '  !insertmacro ${ACTION} "Uninstall.exe"', "!macroend", ""]
    return "\n".join(lines)


def build(payload, output, makensis):
    payload = payload.resolve(strict=True)
    output = output.resolve()
    if output.suffix.lower() != ".exe" or output.is_relative_to(payload):
        raise ValueError("Choose a Setup.exe output outside the source payload folder")
    if not output.parent.is_dir():
        raise ValueError("The output folder must already exist")
    manifest, checked = validate_payload(payload)
    compiler = shutil.which(makensis)
    if not compiler:
        raise ValueError("makensis was not found; install NSIS before building Setup.exe")
    with tempfile.TemporaryDirectory(prefix="fah-nsis-") as temporary:
        include = Path(temporary) / "payload.nsh"
        include.write_text(payload_include(payload, checked))
        subprocess.run([
            compiler, "-V3", "-WX", f'-DFAH_VERSION={manifest["version"]}',
            f"-DFAH_PAYLOAD_INCLUDE={nsis_escape(str(include))}",
            f"-DFAH_OUTPUT={nsis_escape(str(output))}", str(INSTALLER / "FAHSaver.nsi")
        ], check=True)
    if pe_machine(output) not in (0x14C, 0x8664):
        raise ValueError("NSIS did not produce a Windows installer executable")
    result = {
        "product": "FAH Saver", "version": manifest["version"],
        "installer_sha256": sha256(output),
        "installer_source_sha256": sha256(INSTALLER / "FAHSaver.nsi"),
        "payload_files": checked,
        "release_source": manifest.get("source", {}),
        "runtime_verification": "Compilation and payload checks only; run the native lifecycle helper on Windows."
    }
    output.with_suffix(".manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--payload", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--makensis", default="makensis")
    arguments = parser.parse_args()
    result = build(arguments.payload, arguments.output, arguments.makensis)
    print(f'Built {arguments.output}: SHA256 {result["installer_sha256"]}')


if __name__ == "__main__":
    main()
